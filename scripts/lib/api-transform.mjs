export function apigenAnchor(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

// Fenced-code state machine shared by everything that scans lines: a fence of
// three or more backticks or tildes opens, and only a fence of the same
// character and at least the same length closes it (CommonMark).
const FENCE = /^ {0,3}(`{3,}|~{3,})/;
function mapLines(markdown, fn) {
  let fence = null;
  return markdown.split(/\r?\n/).map((line) => {
    const f = FENCE.exec(line);
    if (fence) {
      if (f && f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
      return fn(line, true);
    }
    if (f) { fence = f[1]; return fn(line, true); }
    return fn(line, false);
  });
}

// apigen writes placeholders like `"nodemp:<id>"` and `storage/<resource>.json` in
// prose. Markdown reads a bare `<id>` as an HTML tag and the browser drops it, so
// outside fenced and inline code they become entities. Autolinks (`<https://…>`)
// and anything with a `:` or `/` do not match the identifier pattern.
export function escapeAnglePlaceholders(markdown) {
  return mapLines(markdown, (line, inFence) => {
    if (inFence) return line;
    return line.split(/(`[^`]*`)/).map((seg, i) => (i % 2 ? seg : seg.replace(/<([a-z][a-z0-9_-]*)>/gi, '&lt;$1&gt;'))).join('');
  }).join('\n');
}

function unescapeAngle(text) {
  return text.replace(/&lt;/g, '<').replace(/&gt;/g, '>');
}

// Astro runs remark-smartypants before it ids a heading: outside inline code a
// run of exactly two hyphens becomes an em dash, which github-slugger drops
// (a literal hyphen it keeps). Mirror that, and drop the backticks, so the map
// yields the ids Astro actually emits. Entities are decoded first because the
// parser hands the slugger the decoded text.
function headingText(raw) {
  return unescapeAngle(raw).split('`').map((seg, i) => (i % 2 ? seg : seg.replace(/(?<!-)--(?!-)/g, '\u2014'))).join('');
}

function headings(markdown) {
  const out = [];
  let index = -1;
  mapLines(escapeAnglePlaceholders(markdown), (line, inFence) => {
    index += 1;
    const m = inFence ? null : /^(#{1,6})\s+(.+?)\s*$/.exec(line);
    if (m) out.push({ level: m[1].length, raw: m[2], index });
    return line;
  });
  return out;
}

export function headingMap(markdown) {
  const slugger = new GithubSlugger();
  const map = new Map();
  for (const h of headings(markdown)) {
    const gh = slugger.slug(headingText(h.raw));
    const ap = apigenAnchor(unescapeAngle(h.raw));
    if (!map.has(ap)) map.set(ap, gh);
  }
  return map;
}

function stripH1(markdown) {
  const h1 = headings(markdown).find((h) => h.level === 1);
  const title = h1 ? unescapeAngle(h1.raw).replace(/`/g, '').trim() : '';
  const lines = markdown.split(/\r?\n/);
  if (h1) lines.splice(h1.index, 1);
  return { title, body: lines.join('\n').replace(/^\n+/, '') };
}

// The hand-written guides arrive with the content tasks. Until a target page
// exists its links go to `fallback`, so the build never ships a dead link and
// the links validator stays strict; once the page lands the real link is used.
export function resolveGuideLinks(pageExists, fallback = '/plugins/overview/') {
  return Object.fromEntries(Object.entries(GUIDE_LINKS).map(([g, url]) => [g, pageExists(url) ? url : fallback]));
}

export function transformPage(name, markdown, maps, guideLinks = GUIDE_LINKS) {
  const escaped = escapeAnglePlaceholders(markdown);
  const { title: h1, body } = stripH1(escaped);
  const own = maps[name] || headingMap(escaped);
  let text = body;
  // ../../sdk/api.toml → plain code (the sdk repo is private)
  text = text.replace(/\[`?([^\]`]+)`?\]\(\.\.\/\.\.\/sdk\/api\.toml\)/g, '`$1`');
  // guides/*.md → hand-written pages; a file name as link text becomes the guide's title
  text = text.replace(/\[([^\]]*)\]\((guides\/[a-z-]+\.md)\)/g, (m, label, g) =>
    `[${label === g ? GUIDE_TITLES[g] || label : label}](${guideLinks[g] || '/plugins/overview/'})`);
  // other.md#anchor / other.md → absolute page url (+ re-keyed anchor); same rule for the label
  text = text.replace(/\[([^\]]*)\]\((README|lua|raw|c|events)\.md(#[^)]+)?\)/g, (m, label, page, hash) => {
    const file = page + '.md';
    const url = PAGE_URLS[file];
    const shown = label === file ? PAGE_TITLES[file] : label;
    if (!hash) return `[${shown}](${url})`;
    const key = hash.slice(1);
    const target = (maps[file] || new Map()).get(key) || key;
    return `[${shown}](${url}#${target})`;
  });
  // same-page anchors
  text = text.replace(/\]\(#([^)]+)\)/g, (m, key) => `](#${own.get(key) || key})`);
  const title = TITLES[name] || h1;
  const description = DESCRIPTIONS[name] || '';
  const fm = `---\ntitle: ${yamlString(title)}\ndescription: ${yamlString(description)}\nsidebar:\n  order: ${ORDER[name] ?? 99}\n---\n\n`;
  return { file: PAGE_FILES[name], text: fm + text.trimEnd() + '\n' };
}

// Quote a scalar when YAML would read it as something other than this string:
// indicator characters anywhere, a leading `-`/`?`, or a bare boolean/null/number.
export function yamlString(s) {
  const risky = /[:#'"{}\[\]&*!|>%@`]/.test(s) || /^[-?]/.test(s) || /^(true|false|null|~|\d+(\.\d+)?)$/i.test(s);
  return risky ? JSON.stringify(s) : s;
}

